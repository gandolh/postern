// Postern's filters as data: Gmail's filter form (criteria and actions), the
// blocked senders, and the personal scripts Postern's script runs after its
// own rules. The generator (./generate) writes this as Sieve; the parser
// (./parse) reads back exactly what the generator writes.

/** A size criterion, as Gmail's "Size greater than / less than". Sieve units: K = 1024, M = 1024². */
export interface SizeCriterion {
  comparison: "larger" | "smaller";
  /** A whole number of `unit`s, at least 1. */
  amount: number;
  unit: "B" | "K" | "M";
}

/** What a message must match. Every field given must match (AND); an empty field is no condition. */
export interface FilterCriteria {
  /** From contains any of these (address or name). */
  from: string[];
  /** To or Cc contains any of these. */
  to: string[];
  /** Subject contains this. */
  subject: string;
  /** "Has the words": every word or phrase appears in the subject or the body. */
  words: string[];
  /** "Doesn't have": none of these words or phrases appears in the subject or the body. */
  notWords: string[];
  hasAttachment: boolean;
  size: SizeCriterion | null;
}

/** A label to apply: the mailbox id the script files by, and its name as the fallback. */
export interface FilterLabel {
  id: string;
  /** The label's path ("Work/Clients") when the filter was saved. Used only if the id is gone. */
  name: string;
}

/** What to do with a matching message. */
export interface FilterActions {
  /** Skip the Inbox (archive): into the label applied, else All Mail. */
  archive: boolean;
  markRead: boolean;
  star: boolean;
  label: FilterLabel | null;
  /** Forward a copy to this address (Sieve `redirect :copy`). Not applied to existing mail. */
  forwardTo: string | null;
  /** Delete it: to Trash. */
  delete: boolean;
  /** Never send it to Spam: deliver it even when the spam filter says spam. */
  neverSpam: boolean;
}

export interface MailFilter {
  criteria: FilterCriteria;
  actions: FilterActions;
}

/** Everything Postern's script holds. Order is kept: filters run top to bottom. */
export interface FilterSet {
  filters: MailFilter[];
  /** Blocked sender addresses, lower case, in the order they were blocked. Their mail goes to Spam. */
  blocked: string[];
  /** Personal Sieve scripts Postern did not write, run after Postern's filters (`include :personal`). */
  includes: string[];
}

/** The name of Postern's script on the server. */
export const POSTERN_SCRIPT_NAME = "postern";
/** The first line of every script Postern writes. A script without it was not written by Postern. */
export const GENERATED_MARKER = "# Generated by Postern. Edits here are overwritten.";
/** The format of the script body. The parser reads this version only. */
export const SCRIPT_FORMAT = 1;
/** Stalwart keeps the vacation responder in a script of this name (VacationResponse/set). */
export const VACATION_SCRIPT_NAME = "vacation";

export function emptyCriteria(): FilterCriteria {
  return { from: [], to: [], subject: "", words: [], notWords: [], hasAttachment: false, size: null };
}

export function emptyActions(): FilterActions {
  return { archive: false, markRead: false, star: false, label: null, forwardTo: null, delete: false, neverSpam: false };
}

export function emptyFilterSet(): FilterSet {
  return { filters: [], blocked: [], includes: [] };
}

/** Does the script source start with Postern's marker? */
export function isGenerated(source: string): boolean {
  return source.replace(/^\uFEFF/, "").startsWith(GENERATED_MARKER);
}

// ---- Normalising what people type -------------------------------------------

/** Control characters out (a header value has no line breaks), runs of space to one, trimmed. */
export function cleanText(value: string): string {
  // eslint-disable-next-line no-control-regex
  return value.replace(/[\u0000-\u001f\u007f]+/g, " ").replace(/\s+/g, " ").trim();
}

/**
 * "bob@x.test, carol@y.test" or "bob OR carol" as a list: split on commas,
 * semicolons, "|" and the word OR; empty and repeated entries dropped.
 */
export function splitList(value: string): string[] {
  const out: string[] = [];
  for (const raw of value.split(/\s*(?:[,;|]|\s+OR\s+)\s*/)) {
    const item = cleanText(raw);
    if (item && !out.some((o) => o.toLowerCase() === item.toLowerCase())) out.push(item);
  }
  return out;
}

/** "Has the words" text as words and "quoted phrases" (phrases without their quotes). */
export function splitWords(value: string): string[] {
  const out: string[] = [];
  for (const m of value.matchAll(/"([^"]*)"|([^\s"]+)/g)) {
    const item = cleanText(m[1] ?? m[2] ?? "");
    if (item && !out.includes(item)) out.push(item);
  }
  return out;
}

/** The words back as text: phrases quoted. `splitWords(joinWords(w))` gives `w` back. */
export function joinWords(words: readonly string[]): string {
  return words.map((w) => (/\s/.test(w) ? `"${w}"` : w)).join(" ");
}

/** A plausible single address: something@something, no spaces, quotes, brackets or commas. */
export function isAddress(value: string): boolean {
  return /^[^\s@"<>(),;:\\[\]]+@[^\s@"<>(),;:\\[\]]+$/.test(value);
}

/** A blocked address as stored: trimmed, lower case. */
export function normalizeAddress(value: string): string {
  return cleanText(value).replace(/^<|>$/g, "").toLowerCase();
}

/** The filter with every text field cleaned and lists de-duplicated. Pure. */
export function normalizeFilter(filter: MailFilter): MailFilter {
  const c = filter.criteria;
  const a = filter.actions;
  const list = (items: readonly string[]) => splitList(items.join(","));
  const words = (items: readonly string[]) => {
    const out: string[] = [];
    for (const w of items.map(cleanText)) if (w && !out.includes(w)) out.push(w);
    return out;
  };
  const forward = a.forwardTo === null ? null : normalizeAddress(a.forwardTo) || null;
  return {
    criteria: {
      from: list(c.from),
      to: list(c.to),
      subject: cleanText(c.subject),
      words: words(c.words),
      notWords: words(c.notWords),
      hasAttachment: c.hasAttachment,
      size: c.size && Number.isFinite(c.size.amount) ? { ...c.size, amount: Math.floor(c.size.amount) } : null,
    },
    actions: {
      archive: a.archive,
      markRead: a.markRead,
      star: a.star,
      label: a.label ? { id: a.label.id, name: cleanText(a.label.name) } : null,
      forwardTo: forward,
      delete: a.delete,
      neverSpam: a.neverSpam,
    },
  };
}

/** Is any criterion set? */
export function hasCriteria(c: FilterCriteria): boolean {
  return c.from.length > 0 || c.to.length > 0 || c.subject !== "" || c.words.length > 0 || c.notWords.length > 0 || c.hasAttachment || c.size !== null;
}

/** Is any action chosen? */
export function hasActions(a: FilterActions): boolean {
  return a.archive || a.markRead || a.star || a.label !== null || a.forwardTo !== null || a.delete || a.neverSpam;
}

/** The largest size amount accepted (Sieve numbers are 63-bit; this keeps them readable). */
export const MAX_SIZE_AMOUNT = 1_000_000;

/** Why a (normalised) filter cannot be saved, in words for the person; empty when it can. */
export function filterProblems(filter: MailFilter): string[] {
  const problems: string[] = [];
  const { criteria: c, actions: a } = filter;
  if (!hasCriteria(c)) problems.push("Fill in at least one search criterion.");
  if (c.size && (!Number.isInteger(c.size.amount) || c.size.amount < 1 || c.size.amount > MAX_SIZE_AMOUNT)) {
    problems.push("Size must be a whole number from 1 to 1,000,000.");
  }
  if (!hasActions(a)) problems.push("Choose at least one thing to do with matching messages.");
  if (a.forwardTo !== null && !isAddress(a.forwardTo)) problems.push("The forwarding address doesn't look like an email address.");
  if (a.label && !a.label.id) problems.push("Choose a label to apply.");
  return problems;
}

/** Can this name be included from Postern's script? */
export function isIncludableName(name: string): boolean {
  const n = name.trim().toLowerCase();
  return name.length > 0 && name.length <= 512 && n !== POSTERN_SCRIPT_NAME && n !== VACATION_SCRIPT_NAME;
}

/** The set with blocked addresses normalised and de-duplicated, includes de-duplicated. Pure. */
export function normalizeFilterSet(set: FilterSet): FilterSet {
  const blocked: string[] = [];
  for (const raw of set.blocked) {
    const a = normalizeAddress(raw);
    if (a && !blocked.includes(a)) blocked.push(a);
  }
  const includes: string[] = [];
  for (const name of set.includes) if (isIncludableName(name) && !includes.includes(name)) includes.push(name);
  return { filters: set.filters.map(normalizeFilter), blocked, includes };
}

/** Block an address (no change when it already is). */
export function withBlocked(set: FilterSet, address: string): FilterSet {
  const a = normalizeAddress(address);
  if (!a || set.blocked.includes(a)) return set;
  return { ...set, blocked: [...set.blocked, a] };
}

/** Unblock an address (no change when it isn't blocked). */
export function withoutBlocked(set: FilterSet, address: string): FilterSet {
  const a = normalizeAddress(address);
  if (!set.blocked.includes(a)) return set;
  return { ...set, blocked: set.blocked.filter((b) => b !== a) };
}
