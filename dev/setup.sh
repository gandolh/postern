#!/usr/bin/env bash
# dev/setup.sh — start Postern's local Stalwart and make it ready to seed.
#
#   npm run dev:mail          (this script)
#   npm run dev:mail:reset    stop it and wipe dev/data (dev/setup.sh reset)
#
# Idempotent: run it as often as you like.
#   1. dev/.env: random passwords, written only if missing (0600, git-ignored).
#   2. dev/data/stalwart: the store, handed to Stalwart's uid (2000).
#   3. The container, then plan.ndjson through the CLI, then a restart, because
#      a settings reload does not rebind listeners (as in production).
#   4. alice@postern.test and bob@postern.test, created only if missing.
#   5. dev/accounts.ts: system labels (All Mail included), identities, and
#      alice's labels, each created only if missing.
# Then `npm run dev:seed` fills the mailboxes.
set -euo pipefail

DEV="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$DEV/.env"
DOMAIN="postern.test"
HTTP="http://127.0.0.1:18080"

say()  { printf '\033[1m==>\033[0m %s\n' "$*"; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

compose() {
  # --env-file only when it exists: `reset` may run before dev/.env is written,
  # and docker compose errors on a missing env file. The reset path exports a
  # placeholder admin password for interpolation in that case.
  if [[ -f "$ENV_FILE" ]]; then
    docker compose --project-directory "$DEV" -f "$DEV/docker-compose.yml" --env-file "$ENV_FILE" "$@"
  else
    docker compose --project-directory "$DEV" -f "$DEV/docker-compose.yml" "$@"
  fi
}

wait_ready() {
  local i
  for i in $(seq 1 60); do
    curl -fsS --max-time 3 "$HTTP/healthz/ready" >/dev/null 2>&1 && return 0
    sleep 1
  done
  compose logs --tail 40 stalwart >&2 || true
  die "Stalwart did not become ready on $HTTP within 60 s (log above)."
}

reset() {
  say "Stopping the stack and wiping dev/data ..."
  if [[ ! -f "$ENV_FILE" ]]; then
    # compose refuses to parse the file without the admin password; any value
    # does for `down` and the wipe.
    export STALWART_ADMIN_PASSWORD=unused
  fi
  compose --profile tools down --remove-orphans
  if [[ -d "$DEV/data" ]]; then
    # The store belongs to uid 2000, so this machine's user cannot delete it.
    compose run --rm --entrypoint sh data-owner -c 'rm -rf /mnt/data/stalwart'
    rm -rf "$DEV/data"
  fi
  say "Done. dev/.env is kept; \`npm run dev:mail\` starts over with the same passwords."
}

if [[ "${1:-}" == "reset" ]]; then
  reset
  exit 0
fi
[[ $# -eq 0 ]] || die "usage: bash dev/setup.sh [reset]"

command -v docker >/dev/null || die "docker is not on PATH."
docker info >/dev/null 2>&1 || die "Docker is not running (start Docker Desktop)."
command -v node >/dev/null || die "node is not on PATH."

# --- 1. passwords ----------------------------------------------------------
KEYS=(STALWART_ADMIN_PASSWORD ALICE_PASSWORD BOB_PASSWORD)
if [[ ! -f "$ENV_FILE" ]]; then
  say "Writing dev/.env with random passwords ..."
  (
    umask 077
    {
      echo "# Postern's dev mail server. Generated by dev/setup.sh; git-ignored."
      for key in "${KEYS[@]}"; do printf '%s=%s\n' "$key" "$(openssl rand -hex 24)"; done
    } >"$ENV_FILE"
  )
else
  for key in "${KEYS[@]}"; do
    grep -q "^$key=." "$ENV_FILE" || die "dev/.env has no $key. Delete dev/.env and run \`npm run dev:mail:reset && npm run dev:mail\`."
  done
fi
chmod 600 "$ENV_FILE"
# The CLI container reads these as another uid; a strict umask at checkout
# would otherwise hide them from it.
chmod a+r "$DEV/plan.ndjson" "$DEV/config.json"

# --- 2. the store ------------------------------------------------------------
mkdir -p "$DEV/data"
compose run --rm data-owner

# --- 3. the server and its settings -------------------------------------------
say "Starting Stalwart ..."
compose up -d stalwart
wait_ready
say "Applying dev/plan.ndjson ..."
compose run --rm -T cli apply --quiet --file /plan/plan.ndjson
say "Restarting Stalwart so listener changes take effect ..."
compose restart stalwart
wait_ready

# --- 4. accounts ----------------------------------------------------------------
cli() { compose run --rm -T cli "$@"; }

ensure_account() {
  local name="$1" display="$2" key="$3"
  if cli query Account --where "name=$name" --json | grep -q "\"emailAddress\":\"$name@$DOMAIN\""; then
    echo "  $name@$DOMAIN: present"
    return
  fi
  # The plan is built by node, which reads the password from dev/.env itself,
  # so it never appears on a command line.
  ENV_FILE="$ENV_FILE" node -e '
    const [name, display, key] = process.argv.slice(1);
    process.loadEnvFile(process.env.ENV_FILE);
    const domain = { name: "postern.test", certificateManagement: { "@type": "Manual" },
      dkimManagement: { "@type": "Automatic" }, dnsManagement: { "@type": "Manual" },
      subAddressing: { "@type": "Enabled" } };
    console.log(JSON.stringify({ "@type": "upsert", object: "Domain", matchOn: ["name"], value: { postern: domain } }));
    console.log(JSON.stringify({ "@type": "create", object: "Account", value: { [name]: {
      "@type": "User", name, domainId: "#postern", description: display,
      credentials: { 0: { "@type": "Password", secret: process.env[key] } } } } }));
  ' "$name" "$display" "$key" | cli apply --quiet --stdin
  echo "  $name@$DOMAIN: created"
}

say "Accounts ..."
ensure_account alice "Alice Archer" ALICE_PASSWORD
ensure_account bob "Bob Baker" BOB_PASSWORD

# --- 5. labels and identities ---------------------------------------------------
say "Labels and identities ..."
node "$DEV/accounts.ts"

cat <<EOF

Stalwart is up for Postern development.
  JMAP     $HTTP/jmap/session
  IMAP     127.0.0.1:11143 (plain text)
  SMTP     127.0.0.1:12525 (plain text, delivers to @$DOMAIN)
  Admin    $HTTP/admin/  (user "admin", password STALWART_ADMIN_PASSWORD)
  Accounts alice@$DOMAIN, bob@$DOMAIN  (ALICE_PASSWORD, BOB_PASSWORD)
  Passwords are in dev/.env.
Next: npm run dev:seed
EOF
